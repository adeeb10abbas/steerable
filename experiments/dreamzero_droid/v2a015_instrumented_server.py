#!/usr/bin/env python3
"""Launch the V2-A015 DreamZero action-guidance intervention."""

from __future__ import annotations

import asyncio
import dataclasses
import datetime
import json
import logging
import os
import socket
from pathlib import Path
from typing import Any

import torch
import torch.distributed as dist
import tyro

import v2_instrumented_server as base
import v2_bounded_loader as bounded_loader


LOGGER = logging.getLogger(__name__)
OFFICIAL_ACTION_HEAD_SHA256 = "7193cd73423472aa252bee73bd80e0d673c89d773ec852e90f50154729b50845"
V2A015_ACTION_HEAD_SHA256 = "65dc9873aef37563dedf3787fd7b59e0a6d50e575775e38b70edd9e38489f9b8"


@dataclasses.dataclass
class Args:
    port: int
    model_path: str
    tokenizer_path: str
    future_root: str
    patch_path: str
    expected_patch_sha256: str
    expected_patched_target_sha256: str
    action_cfg_scale: float
    timeout_seconds: int = 50000
    enable_dit_cache: bool = True


class GuidedARDroidPolicy(base.InstrumentedARDroidPolicy):
    """Retain futures and disclose the derived action-guidance intervention."""

    def __init__(
        self,
        *args: Any,
        action_cfg_scale: float,
        patch_sha256: str,
        patched_target_sha256: str,
        **kwargs: Any,
    ) -> None:
        super().__init__(*args, **kwargs)
        self._action_cfg_scale = action_cfg_scale
        self._patch_sha256 = patch_sha256
        self._patched_target_sha256 = patched_target_sha256

    def reset(self, reset_info: dict) -> None:
        completed_index = self._episode_index
        super().reset(reset_info)
        manifest_path = self._future_root / f"episode_{completed_index:03d}" / "future_manifest.json"
        manifest = json.loads(manifest_path.read_text())
        manifest.update(
            {
                "schema_version": "vla-wam-shared-v2-dreamzero-v2a015-future-retention-v1",
                "amendment_id": "V2-A015",
                "instrumentation_role": "behavioral_intervention_plus_future_retention",
                "action_cfg_style_scale": self._action_cfg_scale,
                "video_cfg_scale": 5.0,
                "guidance_formula": "negative_action + scale * (conditional_action - negative_action)",
                "guidance_branch": "released_fixed_visual_quality_negative_prompt",
                "negative_branch_caveat": (
                    "This is CFG-style negative-branch action guidance, not strict empty-text "
                    "classifier-free guidance and not an official DreamZero action-CFG feature."
                ),
                "source_patch_sha256": self._patch_sha256,
                "patched_action_head_sha256": self._patched_target_sha256,
                "claim_boundary": (
                    "Actions are generated by a disclosed derived action-flow intervention. "
                    "Latent tensors and official reset-path decoded MP4s are retained without "
                    "changing the returned action array after model inference."
                ),
            }
        )
        for request in manifest["requests"]:
            request["returned_action"] = request.pop("official_action")
            request["returned_action"]["definition"] = (
                "Action tensor returned by the V2-A015 derived guidance path before the "
                "unchanged client normalization and eight-action execution horizon."
            )
            request["action_cfg_style_scale"] = self._action_cfg_scale
            request["video_cfg_scale"] = 5.0
        manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")


def main(args: Args) -> None:
    if args.port == 5000:
        raise ValueError("V2-A015 prohibits the pre-existing DreamZero port 5000")
    if args.action_cfg_scale not in {1.0, 2.0}:
        raise ValueError("V2-A015 permits action-guidance scales 1.0 and 2.0 only")

    model_path = Path(args.model_path).resolve()
    tokenizer_path = Path(args.tokenizer_path).resolve()
    future_root = Path(args.future_root).resolve()
    patch_path = Path(args.patch_path).resolve()
    if not model_path.is_dir() or not tokenizer_path.is_dir():
        raise FileNotFoundError("Exact model and tokenizer directories must exist")
    if not patch_path.is_file():
        raise FileNotFoundError(f"V2-A015 source patch is absent: {patch_path}")
    patch_sha256 = base._sha256(patch_path)
    if patch_sha256 != args.expected_patch_sha256:
        raise ValueError(
            f"V2-A015 patch hash mismatch: {patch_sha256} != {args.expected_patch_sha256}"
        )
    if args.expected_patched_target_sha256 != V2A015_ACTION_HEAD_SHA256:
        raise ValueError("V2-A015 refuses an unregistered patched action-head hash")

    os.environ["DREAMZERO_ACTION_CFG_SCALE"] = str(args.action_cfg_scale)
    os.environ["ENABLE_DIT_CACHE"] = "true" if args.enable_dit_cache else "false"
    os.environ["ATTENTION_BACKEND"] = "TE"
    torch._dynamo.config.recompile_limit = 800

    device_mesh = base.official.init_mesh()
    rank = dist.get_rank()
    if dist.get_world_size() != 2:
        raise ValueError("V2-A015 requires exactly two DreamZero server ranks")
    if "B200" not in torch.cuda.get_device_name(torch.cuda.current_device()):
        raise ValueError("V2-A015 policy ranks must run on ali-owned B200 GPUs")
    timeout = datetime.timedelta(seconds=args.timeout_seconds)
    signal_group = dist.new_group(backend="gloo", timeout=timeout)
    future_root.mkdir(parents=True, exist_ok=True)
    bounded_contract_path = future_root / f"bounded_loader_rank{rank}.json"
    # The historical loader remains byte-for-byte unchanged and accepts only
    # the released action head. This derived server narrows its construction
    # gate to the single V2-A015 hash before any weights are loaded.
    bounded_loader.OFFICIAL_ACTION_HEAD_SHA256 = V2A015_ACTION_HEAD_SHA256
    base.install_bounded_loader(contract_path=bounded_contract_path)
    policy = base.GrootSimPolicy(
        embodiment_tag=base.EmbodimentTag("oxe_droid"),
        model_path=str(model_path),
        device="cuda",
        device_mesh=device_mesh,
        tokenizer_path_override=str(tokenizer_path),
    )

    bounded_contract = json.loads(bounded_contract_path.read_text())
    suppression = bounded_contract["construction_only_component_suppression"]
    observed_loader_action_hash = suppression.pop("official_action_head_sha256")
    observed_loader_action_path = suppression.pop("official_action_head_path")
    if observed_loader_action_hash != V2A015_ACTION_HEAD_SHA256:
        raise ValueError("Bounded loader did not construct from the V2-A015 action head")
    suppression.update(
        {
            "derived_action_head_path": observed_loader_action_path,
            "derived_action_head_sha256": observed_loader_action_hash,
            "released_action_head_sha256": OFFICIAL_ACTION_HEAD_SHA256,
            "v2a015_exact_hash_override": True,
        }
    )
    bounded_contract.update(
        {
            "schema_version": "vla-wam-shared-v2-dreamzero-v2a015-bounded-loader-v1",
            "amendment_id": "V2-A015",
            "loader_overlay_forward_path_modified": False,
            "model_action_forward_path_modified_by_v2a015": True,
            "model_action_forward_intervention": (
                "negative_action + scale * (conditional_action - negative_action)"
            ),
            "claim_boundary": (
                "The bounded-memory load mechanics are unchanged. Its action-head source "
                "hash gate accepts exactly the disclosed V2-A015 derived forward path."
            ),
        }
    )
    bounded_contract_path.write_text(
        json.dumps(bounded_contract, indent=2, sort_keys=True) + "\n"
    )

    import groot.vla.model.dreamzero.action_head.wan_flow_matching_action_tf as action_module

    patched_target = Path(action_module.__file__).resolve()
    patched_target_sha256 = base._sha256(patched_target)
    if patched_target_sha256 != args.expected_patched_target_sha256:
        raise ValueError(
            "V2-A015 patched action-head hash mismatch: "
            f"{patched_target_sha256} != {args.expected_patched_target_sha256}"
        )
    action_head = policy.trained_model.action_head
    observed_scale = float(action_head.action_cfg_scale)
    if observed_scale != args.action_cfg_scale:
        raise ValueError(
            f"DreamZero action head activated scale {observed_scale}, expected {args.action_cfg_scale}"
        )
    if float(action_head.cfg_scale) != 5.0:
        raise ValueError("V2-A015 freezes released DreamZero video guidance at 5.0")

    if rank == 0:
        contract = {
            "schema_version": "vla-wam-shared-v2-dreamzero-v2a015-server-contract-v1",
            "amendment_id": "V2-A015",
            "official_repository_commit": base.OFFICIAL_COMMIT,
            "model_path": str(model_path),
            "tokenizer_path": str(tokenizer_path),
            "port": args.port,
            "world_size": dist.get_world_size(),
            "visible_device_names": [
                torch.cuda.get_device_name(index)
                for index in range(torch.cuda.device_count())
            ],
            "official_noise_seed": base.OFFICIAL_NOISE_SEED,
            "enable_dit_cache": args.enable_dit_cache,
            "runtime_num_inference_steps": 16,
            "evaluated_dit_steps_with_cache": 8,
            "action_cfg_style_scale": args.action_cfg_scale,
            "video_cfg_scale": 5.0,
            "guidance_formula": "negative_action + scale * (conditional_action - negative_action)",
            "guidance_branch": "released_fixed_visual_quality_negative_prompt",
            "negative_branch_caveat": (
                "This is CFG-style negative-branch action guidance, not strict empty-text "
                "classifier-free guidance and not an official DreamZero action-CFG feature."
            ),
            "source_patch": str(patch_path),
            "source_patch_sha256": patch_sha256,
            "patched_action_head": str(patched_target),
            "patched_action_head_sha256": patched_target_sha256,
            "base_instrumented_server_sha256": base._sha256(Path(base.__file__).resolve()),
            "future_root": str(future_root),
        }
        (future_root / "server_contract.json").write_text(
            json.dumps(contract, indent=2, sort_keys=True) + "\n"
        )
        wrapper = GuidedARDroidPolicy(
            groot_policy=policy,
            signal_group=signal_group,
            future_root=future_root,
            action_cfg_scale=args.action_cfg_scale,
            patch_sha256=patch_sha256,
            patched_target_sha256=patched_target_sha256,
        )
        config = base.PolicyServerConfig(
            image_resolution=(180, 320),
            needs_wrist_camera=True,
            n_external_cameras=2,
            needs_stereo_camera=False,
            needs_session_id=True,
            action_space="joint_position",
        )
        LOGGER.info(
            "Creating DreamZero V2-A015 server on %s:%d at action scale %.1f",
            socket.gethostname(),
            args.port,
            args.action_cfg_scale,
        )
        base.official.RoboarenaServer(
            policy=wrapper,
            server_config=config,
            host="0.0.0.0",
            port=args.port,
        ).serve_forever()
    else:
        server = base.official.WebsocketPolicyServer(
            policy=policy,
            host="0.0.0.0",
            port=args.port,
            metadata={
                "embodiment": "oxe_droid",
                "model_name": "dreamzero_v2a015_action_cfg",
                "model_path": str(model_path),
                "action_cfg_style_scale": args.action_cfg_scale,
            },
            output_dir=None,
            signal_group=signal_group,
        )
        asyncio.run(server._worker_loop())


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, force=True)
    main(tyro.cli(Args))
