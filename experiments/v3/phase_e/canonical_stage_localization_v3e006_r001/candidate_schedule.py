"""Freeze a behavior-blind, matched-direction E004 state-repair schedule.

The source trajectories were historically generated by pi0.5, but this module
makes no model request and never reads a V3-E006-R001 behavioral outcome.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
from typing import Any, Mapping, Sequence

import h5py
import numpy as np

from experiments.v3.phase_e.canonical_stage_localization_v3e006.ood_reference import (
    _quat_inverse_wxyz,
    _quat_multiply_wxyz,
    _quat_normalize_wxyz,
    _quat_rotate_inverse_wxyz,
    normalized_distance,
    state_feature,
)


SCHEMA = "vla-wam-shared-v3e006-r001-matched-direction-candidate-schedule-v1"
REPAIR_ID = "V3-E006-R001"
MAXIMUM_CANDIDATE_PAIRS = 8
MIDLINE_TOLERANCE_M = 0.001
CARRY_MINIMUM_RISE_M = 0.04
ALGORITHM_VERSION = "matched-direction-midpoint-search-v2"
CANDIDATE_SEARCH_SHA256 = "7792c4188f15d812fd2e638e457147cb63333cbf75535fd66b69efe694583dfa"
REGISTRATION_SCHEMA = "vla-wam-shared-v3e006-r001-prospective-state-repair-registration-v1"
REGISTRATION_STATUS = "prospectively_registered_repair_algorithm_before_any_repair_candidate_or_model_request"
ORIGINAL_CLOSURE_SCHEMA = "vla-wam-shared-v3e006-r001-original-closure-binding-v1"
ANCHORS = {
    "canonical_grasp": {"environment_seed": 9521, "left": 30, "right": 31},
    "canonical_carry": {"environment_seed": 9442, "left": 39, "right": 38},
}


class CandidateScheduleError(RuntimeError):
    """The prospective schedule could not be built exactly."""


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise CandidateScheduleError(message)


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def binding(path: Path) -> dict[str, Any]:
    path = Path(path).resolve()
    return {"path": str(path), "bytes": path.stat().st_size, "sha256": sha256_file(path)}


def canonical_json_sha256(value: Any) -> str:
    payload = json.dumps(value, allow_nan=False, separators=(",", ":"), sort_keys=True).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def _verify_original_closure(
    *,
    repair: Mapping[str, Any],
    closure_path: Path,
    original_study_root: Path,
) -> dict[str, Any]:
    closure_path = Path(closure_path).resolve()
    original_study_root = Path(original_study_root).resolve()
    expected_binding = repair["frozen_inputs"]["original_closure_binding"]
    observed_binding = binding(closure_path)
    _require(
        observed_binding["bytes"] == expected_binding["bytes"]
        and observed_binding["sha256"] == expected_binding["sha256"],
        "original closure binding bytes or digest differs from registration",
    )
    closure = json.loads(closure_path.read_text(encoding="utf-8"))
    _require(closure.get("schema_version") == ORIGINAL_CLOSURE_SCHEMA, "original closure schema differs")
    _require(closure.get("original_amendment_id") == "V3-E006", "original closure amendment differs")
    _require(
        closure.get("original_closure_commit") == repair["source_ancestry"]["original_closure_commit"],
        "original closure commit differs",
    )
    files = closure.get("files")
    _require(isinstance(files, list) and len(files) == closure.get("file_count") == 28, "original closure file inventory differs")
    by_path: dict[str, Mapping[str, Any]] = {}
    for row in files:
        relative = str(row["path"])
        _require(relative not in by_path, f"duplicate original closure path: {relative}")
        actual = original_study_root / relative
        _require(actual.is_file(), f"original closure file missing: {actual}")
        _require(actual.stat().st_size == row["bytes"], f"original closure bytes changed: {relative}")
        _require(sha256_file(actual) == row["sha256"], f"original closure digest changed: {relative}")
        by_path[relative] = row
    for name in ("state_contract", "ood_reference", "ood_freeze", "original_results", "original_evidence"):
        expected = repair["frozen_inputs"][name]
        row = by_path.get(str(expected["path"]))
        _require(row is not None, f"{name} absent from original closure")
        _require(row["bytes"] == expected["bytes"] and row["sha256"] == expected["sha256"], f"{name} registration binding differs")
    return {"binding": observed_binding, "verified_file_count": len(files), "original_study_root": str(original_study_root)}


def _load_bound(path: Path, expected: Mapping[str, Any]) -> Any:
    path = Path(path).resolve()
    _require(path.is_file(), f"bound source missing: {path}")
    _require(path.stat().st_size == expected["bytes"], f"bound source bytes changed: {path}")
    _require(sha256_file(path) == expected["sha256"], f"bound source digest changed: {path}")
    return json.loads(path.read_text(encoding="utf-8"))


def _nlerp(left: Sequence[float], right: Sequence[float]) -> np.ndarray:
    a = _quat_normalize_wxyz(left)
    b = _quat_normalize_wxyz(right)
    if float(np.dot(a, b)) < 0.0:
        b = -b
    return _quat_normalize_wxyz(a + b)


def _quat_rotate(quaternion: Sequence[float], vector: Sequence[float]) -> np.ndarray:
    q = _quat_normalize_wxyz(quaternion)
    w, xyz = float(q[0]), q[1:]
    value = np.asarray(vector, dtype=np.float64)
    return 2 * np.dot(xyz, value) * xyz + (w * w - np.dot(xyz, xyz)) * value + 2 * w * np.cross(xyz, value)


def _stage_indices(steps: Sequence[Mapping[str, Any]], cube_positions: np.ndarray, *, stage: str, offset: int) -> list[int]:
    initial_z = float(cube_positions[offset, 2])
    grabbed = [bool(row.get("object_grabbed")) for row in steps]
    grasp_indices = [
        index
        for index in range(2, len(steps))
        if all(grabbed[index - 2 : index + 1])
        and abs(float(cube_positions[offset + index, 1])) < 0.04
        and float(cube_positions[offset + index, 2]) - initial_z < CARRY_MINIMUM_RISE_M
    ]
    if stage == "canonical_grasp":
        return grasp_indices
    if not grasp_indices:
        return []
    first_grasp = grasp_indices[0]
    rows: list[int] = []
    for index in range(first_grasp + 1, len(steps)):
        hdf5_index = offset + index
        rise = float(cube_positions[hdf5_index, 2]) - initial_z
        if not grabbed[index]:
            continue
        if abs(float(cube_positions[hdf5_index, 1])) >= 0.04:
            continue
        if rise >= CARRY_MINIMUM_RISE_M:
            rows.append(index)
    return rows


def _source_states(source: Mapping[str, Any], *, stage: str, reference: Mapping[str, Any]) -> list[dict[str, Any]]:
    state_path = Path(str(source["state_capture"]["path"])).resolve()
    hdf5_path = Path(str(source["hdf5_trace"]["path"])).resolve()
    state_capture = _load_bound(state_path, source["state_capture"])
    for key, path in (("hdf5_trace", hdf5_path), ("raw_episode", Path(str(source["raw_episode"]["path"])).resolve())):
        expected = source[key]
        _require(path.is_file() and path.stat().st_size == expected["bytes"] and sha256_file(path) == expected["sha256"], f"bound {key} changed")
    steps = state_capture["steps"]
    offset = int(source["hdf5_to_state_capture_offset"])
    rows: list[dict[str, Any]] = []
    with h5py.File(hdf5_path, "r") as handle:
        root = handle["data/demo_0"]
        joints = np.asarray(root["states/articulation/robot/joint_position"], dtype=np.float64)
        cube_poses = np.asarray(root["states/rigid_object/rubiks_cube/root_pose"], dtype=np.float64)
        eef_positions = np.asarray(root["ee_pose/position"], dtype=np.float64)
        eef_quaternions = np.asarray(root["ee_pose/orientation"], dtype=np.float64)
        _require(len(joints) - len(steps) == offset == 74, "E004 state/HDF5 alignment changed")
        for state_index in _stage_indices(steps, cube_poses[:, :3], stage=stage, offset=offset):
            hdf5_index = offset + state_index
            feature = state_feature(
                arm_joint_positions_rad=joints[hdf5_index, :7],
                eef_position_world_m=eef_positions[hdf5_index],
                eef_quaternion_world_wxyz=eef_quaternions[hdf5_index],
                cube_position_world_m=cube_poses[hdf5_index, :3],
                cube_quaternion_world_wxyz=cube_poses[hdf5_index, 3:],
            )
            distance = normalized_distance(
                feature,
                center=reference["direction_balanced_center"],
                scale=reference["robust_scale"],
            )
            if distance > float(reference["acceptance"]["maximum_distance_inclusive"]):
                continue
            cube_pose = cube_poses[hdf5_index]
            eef_position = eef_positions[hdf5_index]
            eef_quaternion = eef_quaternions[hdf5_index]
            cube_in_eef_translation = _quat_rotate_inverse_wxyz(eef_quaternion, cube_pose[:3] - eef_position)
            cube_in_eef_quaternion = _quat_multiply_wxyz(_quat_inverse_wxyz(eef_quaternion), cube_pose[3:])
            rows.append(
                {
                    "state_capture_index": state_index,
                    "hdf5_index": hdf5_index,
                    "joint_position_rad": joints[hdf5_index].tolist(),
                    "cube_pose_world_wxyz": cube_pose.tolist(),
                    "eef_position_world_m": eef_position.tolist(),
                    "eef_quaternion_world_wxyz": eef_quaternion.tolist(),
                    "cube_in_eef_translation_m": cube_in_eef_translation.tolist(),
                    "cube_in_eef_quaternion_wxyz": cube_in_eef_quaternion.tolist(),
                    "ood_distance": distance,
                }
            )
    return rows


def _pair_row(*, stage: str, seed: int, left: Mapping[str, Any], right: Mapping[str, Any], sources: Mapping[str, Mapping[str, Any]]) -> dict[str, Any] | None:
    left_cube = np.asarray(left["cube_pose_world_wxyz"], dtype=np.float64)
    right_cube = np.asarray(right["cube_pose_world_wxyz"], dtype=np.float64)
    cube_position = (left_cube[:3] + right_cube[:3]) / 2.0
    if abs(float(cube_position[1])) >= MIDLINE_TOLERANCE_M:
        return None
    cube_position[1] = 0.0
    cube_quaternion = _nlerp(left_cube[3:], right_cube[3:])
    joint_left = np.asarray(left["joint_position_rad"], dtype=np.float64)
    joint_right = np.asarray(right["joint_position_rad"], dtype=np.float64)
    joint_midpoint = (joint_left + joint_right) / 2.0
    translation = (
        np.asarray(left["cube_in_eef_translation_m"], dtype=np.float64)
        + np.asarray(right["cube_in_eef_translation_m"], dtype=np.float64)
    ) / 2.0
    relative_quaternion = _nlerp(left["cube_in_eef_quaternion_wxyz"], right["cube_in_eef_quaternion_wxyz"])
    eef_quaternion = _quat_multiply_wxyz(cube_quaternion, _quat_inverse_wxyz(relative_quaternion))
    eef_position = cube_position - _quat_rotate(eef_quaternion, translation)
    joint_delta = joint_left[:7] - joint_right[:7]
    eef_delta = np.asarray(left["eef_position_world_m"]) - np.asarray(right["eef_position_world_m"])
    maximum_ood = max(float(left["ood_distance"]), float(right["ood_distance"]))
    return {
        "stage": stage,
        "environment_seed": seed,
        "source_states": {
            "left": {**dict(left), "provenance": dict(sources["left"])},
            "right": {**dict(right), "provenance": dict(sources["right"])},
        },
        "direction_balanced_state": {
            "joint_position_rad": joint_midpoint.tolist(),
            "joint_velocity_rad_s": [0.0] * len(joint_midpoint),
            "cube_pose_world_wxyz": np.concatenate((cube_position, cube_quaternion)).tolist(),
            "cube_velocity_world": [0.0] * 6,
            "composed_eef_pose_diagnostic_only": {
                "position_world_m": eef_position.tolist(),
                "quaternion_world_wxyz": eef_quaternion.tolist(),
            },
            "cube_in_eef_translation_m": translation.tolist(),
            "cube_in_eef_quaternion_wxyz": relative_quaternion.tolist(),
        },
        "ranking_metrics": {
            "maximum_source_ood_distance": maximum_ood,
            "absolute_midpoint_cube_y_before_zero_m": abs(float(((left_cube[:3] + right_cube[:3]) / 2.0)[1])),
            "arm_joint_rms_difference_rad": float(np.sqrt(np.mean(np.square(joint_delta)))),
            "arm_joint_maximum_absolute_difference_rad": float(np.max(np.abs(joint_delta))),
            "eef_position_difference_m": float(np.linalg.norm(eef_delta)),
        },
    }


def _best_pair_for_seed(*, stage: str, seed: int, left_rows: Sequence[Mapping[str, Any]], right_rows: Sequence[Mapping[str, Any]], sources: Mapping[str, Mapping[str, Any]]) -> dict[str, Any] | None:
    candidates = [
        row
        for left in left_rows
        for right in right_rows
        if (row := _pair_row(stage=stage, seed=seed, left=left, right=right, sources=sources)) is not None
    ]
    if not candidates:
        return None
    return min(
        candidates,
        key=lambda row: (
            row["ranking_metrics"]["arm_joint_rms_difference_rad"],
            row["ranking_metrics"]["eef_position_difference_m"],
            row["ranking_metrics"]["absolute_midpoint_cube_y_before_zero_m"],
            row["source_states"]["left"]["state_capture_index"],
            row["source_states"]["right"]["state_capture_index"],
        ),
    )


def build(
    *,
    registration: Path,
    ood_freeze: Path,
    original_closure_binding: Path,
    original_study_root: Path,
    output: Path,
) -> dict[str, Any]:
    registration = Path(registration).resolve()
    ood_freeze = Path(ood_freeze).resolve()
    output = Path(output).resolve()
    _require(not output.exists(), f"refusing to overwrite schedule: {output}")
    repair = json.loads(registration.read_text(encoding="utf-8"))
    _require(repair.get("schema_version") == REGISTRATION_SCHEMA, "repair registration schema differs")
    _require(repair.get("status") == REGISTRATION_STATUS, "repair registration status differs")
    _require(repair["repair_amendment_id"] == REPAIR_ID, "repair registration differs")
    _require(repair["candidate_search"].get("algorithm_version") == ALGORITHM_VERSION, "candidate algorithm version differs")
    _require(canonical_json_sha256(repair["candidate_search"]) == CANDIDATE_SEARCH_SHA256, "candidate-search contract text differs")
    _require(repair["candidate_search"].get("maximum_candidate_pairs") == MAXIMUM_CANDIDATE_PAIRS, "candidate budget differs")
    _require(repair["counts_at_registration"] == {"behavioral_episodes": 0, "model_requests": 0, "repair_candidate_evaluations": 0}, "registration counts are not zero")
    original_closure = _verify_original_closure(
        repair=repair,
        closure_path=original_closure_binding,
        original_study_root=original_study_root,
    )
    frozen = repair["frozen_inputs"]["ood_freeze"]
    observed_freeze = binding(ood_freeze)
    _require(
        observed_freeze["bytes"] == frozen["bytes"] and observed_freeze["sha256"] == frozen["sha256"],
        "OOD freeze bytes or digest differs from registration",
    )
    ood = json.loads(ood_freeze.read_text(encoding="utf-8"))
    sources_by_seed: dict[int, dict[str, Mapping[str, Any]]] = {}
    for source in ood["source_provenance"]:
        sources_by_seed.setdefault(int(source["environment_seed"]), {})[str(source["requested_relation"])] = source
    stage_rankings: dict[str, list[dict[str, Any]]] = {}
    for stage in ("canonical_grasp", "canonical_carry"):
        paired: list[dict[str, Any]] = []
        anchor_row: dict[str, Any] | None = None
        anchor = ANCHORS[stage]
        for seed, directions in sorted(sources_by_seed.items()):
            if set(directions) != {"left", "right"}:
                continue
            left_rows = _source_states(directions["left"], stage=stage, reference=ood["stages"][stage])
            right_rows = _source_states(directions["right"], stage=stage, reference=ood["stages"][stage])
            if seed == anchor["environment_seed"]:
                left_anchor = [row for row in left_rows if row["state_capture_index"] == anchor["left"]]
                right_anchor = [row for row in right_rows if row["state_capture_index"] == anchor["right"]]
                _require(len(left_anchor) == len(right_anchor) == 1, f"registered {stage} anchor source is unavailable")
                anchor_row = _pair_row(
                    stage=stage,
                    seed=seed,
                    left=left_anchor[0],
                    right=right_anchor[0],
                    sources=directions,
                )
                _require(anchor_row is not None, f"registered {stage} anchor violates midpoint tolerance")
                continue
            best = _best_pair_for_seed(stage=stage, seed=seed, left_rows=left_rows, right_rows=right_rows, sources=directions)
            if best is not None:
                paired.append(best)
        paired.sort(
            key=lambda row: (
                row["ranking_metrics"]["arm_joint_rms_difference_rad"],
                row["ranking_metrics"]["eef_position_difference_m"],
                row["ranking_metrics"]["absolute_midpoint_cube_y_before_zero_m"],
                row["ranking_metrics"]["maximum_source_ood_distance"],
                row["environment_seed"],
            )
        )
        _require(anchor_row is not None, f"registered {stage} anchor was not found")
        _require(len(paired) >= MAXIMUM_CANDIDATE_PAIRS - 1, f"fewer than eight eligible matched {stage} pairs")
        stage_rankings[stage] = [anchor_row, *paired[: MAXIMUM_CANDIDATE_PAIRS - 1]]
    candidate_pairs = [
        {
            "candidate_rank": index + 1,
            "canonical_grasp": stage_rankings["canonical_grasp"][index],
            "canonical_carry": stage_rankings["canonical_carry"][index],
        }
        for index in range(MAXIMUM_CANDIDATE_PAIRS)
    ]
    result = {
        "schema_version": SCHEMA,
        "repair_amendment_id": REPAIR_ID,
        "status": "frozen_before_any_live_repair_candidate_or_new_model_request",
        "model_request_count": 0,
        "repair_behavioral_episode_count": 0,
        "repair_registration": binding(registration),
        "ood_freeze": binding(ood_freeze),
        "original_closure_verification": original_closure,
        "candidate_budget": MAXIMUM_CANDIDATE_PAIRS,
        "candidate_pairs": candidate_pairs,
        "ranking_and_selection": repair["candidate_search"],
        "historical_policy_provenance_disclosure": "Sources are successful historical E004 pi0.5 trajectories; schedule generation and all R001 live candidate checks make no new model request and inspect no R001 policy behavior.",
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(result, allow_nan=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--registration", type=Path, required=True)
    parser.add_argument("--ood-freeze", type=Path, required=True)
    parser.add_argument("--original-closure-binding", type=Path, required=True)
    parser.add_argument("--original-study-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    result = build(
        registration=args.registration,
        ood_freeze=args.ood_freeze,
        original_closure_binding=args.original_closure_binding,
        original_study_root=args.original_study_root,
        output=args.output,
    )
    print(json.dumps({"output": str(args.output.resolve()), "sha256": sha256_file(args.output), "candidate_pairs": len(result["candidate_pairs"])}, sort_keys=True))


if __name__ == "__main__":
    main()
